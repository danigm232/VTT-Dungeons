"""Measure alpha components, never rewrite artwork. Emits reproducible crop metadata."""
from pathlib import Path
from collections import deque
import json, sys
import numpy as np
from PIL import Image

root=Path(__file__).resolve().parents[1]
folder=root/'campaigns/one-shot/public/art/silverfarben-v3'
specs={name:(5,6) for name in ['run6','spell6','jump6','dagger6']}
specs.update({name:(3,6) for name in ['gestures6','utility6','reactions6']})
specs['conditions3']=(4,6)
specs.update({f'run-{direction}6':(2,3) for direction in ['n','ne','e','se','s']})
specs.update({name:(2,3) for name in ['bow6','unarmed6','throw6']})
specs['model']=(1,5)
specs['torch6']=(2,3)

def components(alpha):
    """Four-connected alpha components, matching the renderer (no SciPy needed)."""
    h,w=alpha.shape; data=alpha.tobytes(); seen=bytearray(w*h)
    labels=np.zeros((h,w),dtype=np.int32); flat=labels.ravel(); parts=[]
    for start in range(w*h):
        if data[start]<32 or seen[start]:continue
        number=len(parts)+1; seen[start]=1;q=deque([start]);area=0
        x0=x1=start%w;y0=y1=start//w
        while q:
            p=q.popleft();x,y=p%w,p//w;flat[p]=number;area+=1
            x0=min(x0,x);x1=max(x1,x);y0=min(y0,y);y1=max(y1,y)
            for n in (p-1 if x else -1,p+1 if x+1<w else -1,p-w if y else -1,p+w if y+1<h else -1):
                if n>=0 and not seen[n] and data[n]>=32:seen[n]=1;q.append(n)
        parts.append({'box':[x0,y0,x1+1,y1+1],'area':area,'seed':[start%w,start//w],'label':number})
    return labels,parts

result={}; summary={}
for name,(rows,cols) in specs.items():
    path=folder/f'{name}.png'
    if not path.exists():continue
    im=Image.open(path).convert('RGBA');w,h=im.size
    a=np.asarray(im)[:,:,3]
    if any(a[y,x]>=32 for x,y in [(0,0),(w-1,0),(0,h-1),(w-1,h-1)]):raise RuntimeError(f'Opaque background: {name}')
    labels,objects=components(a)
    if '--debug' in sys.argv:print(name,[(p['box'],p['area']) for p in objects if p['area']>1000],flush=True)
    groups=[[] for _ in range(rows*cols)]
    for part in objects:
        if part['area']<8:continue
        x,y,r,b=part['box']
        # Detached arrows/daggers belong to the world projectile, not a body
        # crop (nor the neighbouring pose whose cell they may cross).
        if name in ['bow6','throw6'] and b-y<h/rows*.1 and r-x>w/cols*.1:continue
        row=min(rows-1,int((y+b)/2/h*rows));col=min(cols-1,int((x+r)/2/w*cols))
        groups[row*cols+col].append(part)
    frames=[];heights=[]
    for i,parts in enumerate(groups):
        parts.sort(key=lambda part:-part['area']);parts=parts[:12]
        if not parts or parts[0]['area']<1000:raise RuntimeError(f'Empty/incorrect cell: {name}/{i}')
        body=parts[0];bx,by,br,bb=body['box']
        max_height=h/rows*(1.4 if name=='conditions3' else 1.15)
        if br-bx>w/cols*1.45 or bb-by>max_height:raise RuntimeError(f'Connected neighbours: {name}/{i}: {body["box"]}')
        x=max(0,min(p['box'][0] for p in parts)-2);y=max(0,min(p['box'][1] for p in parts)-2)
        r=min(w,max(p['box'][2] for p in parts)+2);b=min(h,max(p['box'][3] for p in parts)+2)
        band=labels[by+int((bb-by)*.46):by+int((bb-by)*.62),bx:br]==body['label']
        points=np.argwhere(band)
        pivot=bx+float(points[:,1].mean()) if len(points) else (bx+br)/2
        frames.append({'url':f'/art/silverfarben-v3/{name}.png','x':x,'y':y,'width':r-x,'height':b-y,
            'anchorX':round((pivot-x)/(r-x),6),'anchorY':round((bb-y)/(b-y),6),
            'alphaSeeds':[[p['seed'][0]-x,p['seed'][1]-y] for p in parts]})
        heights.append(bb-by)
    refs=[]
    for row in range(rows):
        hs=heights[row*cols:(row+1)*cols]
        # A single ISOTROPIC scale for the whole row: crouching never stretches
        # back to standing height, nor do arms/book change the body's scale.
        reference=max(hs) if name in ['jump6','run6'] else hs[0]
        logical=86 if name=='run6' else 92
        if name=='conditions3':reference=float(np.median(heights[6:9]));logical=92
        if name.startswith('run-'):reference=max(heights);logical=86
        if name in ['gestures6','utility6','reactions6']:reference=max(heights)
        if name in ['bow6','unarmed6','throw6','torch6']:reference=heights[0]
        refs.append(reference)
        for f in frames[row*cols:(row+1)*cols]:
            f['logicalWidth']=round(f['width']*logical/reference,6)
            f['logicalHeight']=round(f['height']*logical/reference,6)
    result[name]={'size':[w,h],'rows':rows,'columns':cols,'referenceHeights':refs,'frames':frames}
    summary[name]={'size':[w,h],'frames':len(frames),'seeds':max(len(f['alphaSeeds']) for f in frames)}
dest=root/'campaigns/one-shot/public/silverfarben-frames-v3.ts'
dest.write_text('// Generated by scripts/build-silverfarben-frames.py from alpha components.\nexport const silverfarbenFramesV3 = '+json.dumps(result,indent=2)+';\n',encoding='utf-8')
out=root/'output/silverfarben-audit-20261020';out.mkdir(exist_ok=True,parents=True)
(out/'measured-frames.json').write_text(json.dumps(result,indent=2),encoding='utf-8')
print(json.dumps(summary))
