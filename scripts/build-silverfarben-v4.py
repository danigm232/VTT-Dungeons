"""Generate measurements for the nine requested replacement actions; no PNG edits."""
from pathlib import Path
import argparse,json
from PIL import Image
from sprite_alpha_components import measure_atlas

root=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser();parser.add_argument('--allow-partial',action='store_true');args=parser.parse_args()
folder=root/'campaigns/one-shot/public/art/silverfarben-v4'
spec=json.loads((folder/'spec.json').read_text(encoding='utf-8'));result={};missing=[]
for name,settings in spec.items():
    path=folder/f'{name}.png'
    if not path.exists():missing.append(name);continue
    reference=settings.get('referenceHeight')
    if reference=='horizontal':
        with Image.open(path) as source:reference=source.width/settings['columns']*.78
    atlas=measure_atlas(path,f'/art/silverfarben-v4/{name}.png',settings['rows'],settings['columns'],reference,
        pivot_band=(.3,.7) if settings.get('horizontal') else (.58,.78))
    if len(atlas['frames'])<6:raise ValueError(f'{name}: minimum six poses not met')
    atlas['phases']=settings['phases'];result[name]=atlas
if missing and not args.allow_partial:raise ValueError(f'Missing accepted PNGs: {missing}')
destination=root/'campaigns/one-shot/public/silverfarben-frames-v4.ts'
destination.write_text('// Generated by scripts/build-silverfarben-v4.py; source PNGs are unchanged.\nexport const silverfarbenFramesV4 = '+json.dumps(result,indent=2)+';\n',encoding='utf-8')
output=root/'output/silverfarben-v4';output.mkdir(parents=True,exist_ok=True)
(output/'measurements.json').write_text(json.dumps(result,indent=2),encoding='utf-8')
print(json.dumps({'atlases':len(result),'poses':sum(len(a['frames']) for a in result.values()),'missing':missing}))
