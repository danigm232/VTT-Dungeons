import type { PublicCampaignDefinition } from '../../../engine/shared/campaign.js';
// 20261004 supplement: quadruped/plant gestures and player fall/rise sequences.
type AtlasFrame = Exclude<PublicCampaignDefinition['tokenAnimations'][string][string]['frames'][number], string>;
export function completeD8Animations(campaign: PublicCampaignDefinition) {
  const directions = ['n', 'ne', 'e', 'se', 's', 'sw', 'w', 'nw'];
  for (const [tokenId, atlas] of Object.entries(d8CompletionAtlases)) {
    for (const id of tokenId === 'anteros' ? ['anteros', 'anteros-dinner'] : [tokenId]) {
      const states = campaign.tokenAnimations[id]!;
      const cycle = (frames: AtlasFrame[], row: number, fps = 7) => ({ frames: frames.slice(row * 4, row * 4 + 4), fps });
      if (atlas.actions) {
        const frames = atlas.actions;
        Object.assign(states, { jump: { ...cycle(frames, 0, 6), motion: 'jump' as const }, climb: { ...cycle(frames, 1), motion: 'climb' as const }, swim: { ...cycle(frames, 2), motion: 'swim' as const }, dodge: { ...cycle(frames, 3), motion: 'dodge' as const }, stealth: cycle(frames, 4), search: cycle(frames, 5, 5), ready: cycle(frames, 6, 5), interact: cycle(frames, 7, 6) });
        // Shared expressive gestures are deliberately reported as reused, not new powers.
        states.study = states.search!; states.talk ??= states.interact!; states.spell ??= states.ready!;
        if (frames.length >= 40) atlas.rise = frames.slice(32, 40);
      }
      if (atlas.rise) {
        states.fall = cycle(atlas.rise, 0); states.stand = cycle(atlas.rise, 1);
        states.prone ??= { frames: states.fall.frames.slice(-1), fps: 1 };
        states.defeated ??= states.prone; states['idle-standing'] = { frames: states.stand.frames.slice(-1), fps: 1 };
      }
      if (atlas.unarmed) states['attack-unarmed'] = { frames: atlas.unarmed, fps: 7 };
      if (atlas.run) {
        for (const [row, direction] of directions.entries()) {
          states[`running-${direction}`] = cycle(atlas.run, row, 11);
          states[`direction-${direction}`] ??= cycle(atlas.run, row, 6);
        }
        states.running = states['running-s']!;
      }
      states.disengage = { ...states.moving!, motion: 'disengage' };
      // A cow's existing buck/resistance gesture is anatomical, not a humanoid punch.
      if (id === 'cow') states.attack ??= states.resist ?? states.interact!;
      for (const direction of directions) if (states[`direction-${direction}`]) states[`disengage-${direction}`] = { ...states[`direction-${direction}`]!, motion: 'disengage' };
    }
  }
  for (const id of ['rogue', 'silverfarben-hotel']) {
    const states = campaign.tokenAnimations[id]!;
    for (const [name, motion] of [['jump', 'jump'], ['dodge', 'dodge'], ['swim', 'swim'], ['climb', 'climb']] as const) if (states[name]) states[name] = { ...states[name]!, motion };
  }
  for (const states of Object.values(campaign.tokenAnimations)) if (states.attack) states['attack-unarmed'] ??= states.attack;
}
